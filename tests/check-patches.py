#!/usr/bin/env python3
"""Reconstruct the known-good patched files from a local synced checkout's HEADs.

This never edits the checkout. Only tracked files referenced by patches are read;
there are no signing keys or proprietary binary files in the patch fixtures.
"""
import argparse
import importlib.util
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('checkout', type=Path)
args = parser.parse_args()
source = args.checkout.resolve()
root = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('apply_patches', root / 'scripts/apply-patches.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
series = module.load_series(root, 'lemonades')
projects = sorted((p.get('path', p.get('name')) for p in
                   ET.parse(root / 'manifests/known-good.xml').getroot().findall('project')),
                  key=len, reverse=True)
paths = set()
for entry in series:
    patch = root / 'patches' / entry['patch']
    for line in patch.read_text().splitlines():
        if line.startswith(('--- a/', '+++ b/')):
            paths.add(Path(entry['project']) / line[6:].split('\t')[0])

with tempfile.TemporaryDirectory(prefix='axion-patch-check-') as directory:
    target = Path(directory)
    for path in paths:
        project = next((p for p in projects if str(path).startswith(p + '/')), None)
        if project is None:
            raise RuntimeError(f'No project in manifest for {path}')
        relative = path.relative_to(project)
        original = subprocess.run(['git', 'show', f'HEAD:{relative}'], cwd=source / project,
                                  capture_output=True)
        destination = target / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if original.returncode == 0:
            destination.write_bytes(original.stdout)
            mode = subprocess.check_output(['git', 'ls-tree', 'HEAD', '--', str(relative)],
                                           cwd=source / project, text=True).split()[0]
            if mode == '100755':
                destination.chmod(0o755)
    module.apply_series(target, root)
    # Applying twice must recognize the existing changes, never double-apply.
    module.apply_series(target, root)
    for path in paths:
        expected, actual = source / path, target / path
        assert expected.exists() == actual.exists(), f'Existence mismatch: {path}'
        if expected.exists():
            expected_bytes = expected.read_bytes()
            # This one line is generated by ika's provisioning function, not a
            # source patch. Compare the source layer before that runtime step.
            if str(path) == 'trusty/vendor/google/aosp/scripts/Android.bp':
                expected_bytes = expected_bytes.replace(
                    b'        ":trusty_dirgroup_prebuilts_clang_host_linux-arm64",\n', b'')
            assert expected_bytes == actual.read_bytes(), f'Content mismatch: {path}'
    print(f'PASS: {len(series)} ordered patches; {len(paths)} paths match working tree '
          '(excluding ika-generated Trusty dirgroup reference); idempotent')
